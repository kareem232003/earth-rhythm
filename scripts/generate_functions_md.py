"""Automated AST parser to generate functions.md from all Python files in the project."""

from __future__ import annotations

import ast
from pathlib import Path
from typing import List, Tuple

EXCLUDED_DIRS = {".venv", "venv", "node_modules", "__pycache__", ".git", "dist", "build"}


def iter_python_files(root: Path) -> List[Path]:
    """Return sorted list of Python files in the project, excluding virtualenvs and build dirs."""
    py_files: List[Path] = []
    for path in root.rglob("*.py"):
        if any(part in EXCLUDED_DIRS for part in path.parts):
            continue
        py_files.append(path)
    return sorted(py_files)


def format_signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """Format a function or method signature including argument names and return annotation."""
    args = [arg.arg for arg in node.args.args]
    if node.args.vararg:
        args.append(f"*{node.args.vararg.arg}")
    for kwarg in node.args.kwonlyargs:
        args.append(f"{kwarg.arg}=...")
    if node.args.kwarg:
        args.append(f"**{node.args.kwarg.arg}")
    ret = ""
    if node.returns is not None:
        try:
            ret = f" -> {ast.unparse(node.returns)}"
        except Exception:
            ret = ""
    prefix = "async def " if isinstance(node, ast.AsyncFunctionDef) else "def "
    return f"{prefix}{node.name}({', '.join(args)}){ret}"


def parse_file(py_file: Path, root: Path) -> Tuple[str, List[Tuple[str, int, str]]]:
    """Parse a Python file and extract module docstring plus all classes and functions."""
    source = py_file.read_text(encoding="utf-8", errors="replace")
    tree = ast.parse(source, filename=str(py_file))
    module_doc = (ast.get_docstring(tree) or "No module docstring.").strip().splitlines()[0]
    entries: List[Tuple[str, int, str]] = []

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            doc = (ast.get_docstring(node) or "No docstring.").strip().splitlines()[0]
            entries.append((format_signature(node), node.lineno, doc))
        elif isinstance(node, ast.ClassDef):
            cdoc = (ast.get_docstring(node) or "No docstring.").strip().splitlines()[0]
            entries.append((f"class {node.name}", node.lineno, cdoc))
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    mdoc = (ast.get_docstring(item) or "No docstring.").strip().splitlines()[0]
                    entries.append((f"  {format_signature(item)}", item.lineno, mdoc))

    return module_doc, entries


def generate_functions_md(root: Path, output_path: Path) -> None:
    """Scan the repository and write the automated API directory to functions.md."""
    py_files = iter_python_files(root)
    lines: List[str] = [
        "# Automated Function & Class Directory (`functions.md`)",
        "",
        "> Auto-generated by `scripts/generate_functions_md.py`. Do not edit manually.",
        "",
    ]

    for py_file in py_files:
        rel_path = py_file.relative_to(root).as_posix()
        module_doc, entries = parse_file(py_file, root)
        lines.append(f"## `{rel_path}`")
        lines.append(f"**Summary:** {module_doc}")
        lines.append("")
        if not entries:
            lines.append("_No top-level classes or functions defined._")
            lines.append("")
            continue
        lines.append("| Symbol | Line | Description |")
        lines.append("| :--- | :--- | :--- |")
        for sig, lineno, doc in entries:
            safe_doc = doc.replace("|", "\\|")
            lines.append(f"| `{sig}` | {lineno} | {safe_doc} |")
        lines.append("")

    output_path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    project_root = Path(__file__).resolve().parent.parent
    generate_functions_md(project_root, project_root / "functions.md")
    print(f"Generated {project_root / 'functions.md'}")

